create table alumnos (
  dni varchar(8) primary key,
  nombre varchar(40) not null,
  apellido varchar(40) not null,
  email varchar(60) not null unique,
  telefono varchar(15) not null,
  anio varchar(10) not null,
  division varchar(10) not null default '1° Div',
  estado varchar(15) not null default 'Activo',
  foto text,
  descripcion varchar(200) not null default '',
  creado_en timestamptz default now()
);

create table computadoras (
  id varchar(40) primary key,
  nombre varchar(30) not null unique,
  marca varchar(30) not null,
  modelo varchar(40) not null,
  ram varchar(10) default '—',
  almacenamiento varchar(20) default '—',
  estado varchar(15) not null default 'Disponible'
);

-- on delete set null: se puede borrar un alumno o equipo y el historial se conserva
create table prestamos (
  id bigint generated by default as identity primary key,
  pc_id varchar(40) references computadoras(id) on update cascade on delete set null,
  dni varchar(8) references alumnos(dni) on update cascade on delete set null,
  fecha timestamptz not null default now(),
  devuelto timestamptz
);

-- Seguridad a Nivel de Fila (RLS)
alter table alumnos enable row level security;
alter table computadoras enable row level security;
alter table prestamos enable row level security;

create policy "acceso alumnos" on alumnos for all using (true);
create policy "acceso computadoras" on computadoras for all using (true);
create policy "acceso prestamos" on prestamos for all using (true);

